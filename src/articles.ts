// Время чтения: около 160 слов в минуту для русского текста с кодом и схемами
export function readingMinutes(a: Article) {
  const text = a.lead + " " + a.blocks.map((b) => Object.values(b).flat().map((v) => (typeof v === "string" ? v : JSON.stringify(v))).join(" ")).join(" ");
  const words = text.split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / 160));
}
